import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const store=fs.readFileSync(new URL('../js/store.js',import.meta.url),'utf8');
const app=fs.readFileSync(new URL('../js/app.js',import.meta.url),'utf8');
const writes=[];
const context=vm.createContext({db:{},serverTimestamp:()=>0,collection:(_db,name)=>name,doc:(...parts)=>({path:parts.filter(part=>typeof part==='string').join('/')}),runTransaction:async(_db,fn)=>fn({get:async()=>({exists:()=>true,data:()=>({makeupBalance:2})}),update:(ref,data)=>writes.push({type:'update',ref,data}),set:(ref,data)=>writes.push({type:'set',ref,data})})});
vm.runInContext(store.replace(/^import .*;\r?\n/gm,'').replace(/\bexport /g,''),context);
const call=(balance,reason)=>vm.runInContext(`setStudentMakeupBalance('student-1',${JSON.stringify(balance)},${JSON.stringify(reason)},{uid:'admin'})`,context);
assert.equal((await call(4,'Đối chiếu sổ nghỉ')).delta,2);
assert.equal(writes.find(item=>item.type==='update').data.makeupBalance,4);
assert.equal(writes.find(item=>item.data.type==='manual_adjustment').data.quantity,2);
assert.equal(writes.find(item=>item.data.action==='makeup_balance_adjusted').data.before.makeupBalance,2);
const count=writes.length;assert.equal((await call(2,'Không đổi')).changed,false);assert.equal(writes.length,count);
await assert.rejects(call(-1,'Sai'),/số nguyên/);
await assert.rejects(call(3,''),/lý do/);
assert.ok(app.includes('id="editStudentMakeupBalance"'));
assert.ok(app.includes('function openStudentMakeupBalanceForm'));
assert.ok(app.includes('setStudentMakeupBalance(person.id'));
console.log('PASS: profile balance edit validates, writes atomic ledger and audit, and leaves scheduled sessions untouched');
