import fs from 'node:fs';
import assert from 'node:assert/strict';
const app=fs.readFileSync(new URL('../js/app.js',import.meta.url),'utf8');
const store=fs.readFileSync(new URL('../js/store.js',import.meta.url),'utf8');
assert.ok(app.includes('Đã xếp lịch · Đổi cô'));
assert.ok(app.includes('function openMakeupTeacherReassign'));
assert.ok(app.includes('reassignMakeupSessionTeacher(session.weekId,session.id'));
assert.ok(app.includes('＋ Chọn giáo viên'));
assert.ok(app.includes('function openUnassignedSessionTeacherPicker'));
assert.ok(app.includes('assignUnassignedSessionTeacher(session.weekId,session.id'));
const fn=store.slice(store.indexOf('export async function reassignMakeupSessionTeacher'),store.indexOf('export async function replaceStudentSessionsWithMakeupByName'));
assert.ok(fn.includes('makeup_scheduled'));
assert.ok(fn.includes('Giáo viên đang có buổi khác trùng giờ'));
assert.ok(fn.includes('Giáo viên đang nghỉ phép'));
assert.ok(fn.includes('action:"makeup_teacher_reassigned"'));
const unassigned=store.slice(store.indexOf('export async function assignUnassignedSessionTeacher'),store.indexOf('export async function replaceStudentSessionsWithMakeupByName'));
assert.ok(unassigned.includes('patch.teacherLeaveAction="replacement"'));
assert.ok(unassigned.includes('action:"unassigned_teacher_selected"'));
console.log('PASS: scheduled makeup reopens teacher picker and safely persists reassignment');
